import { readFileSync } from 'node:fs';
import { parse, stringify } from 'yaml';

export const GENERATED_HEADER = '# Code generated by scripts/gateway/render.mjs. DO NOT EDIT.';
export const ROUTES_FILE = 'infra/gateway/routes.yaml';
export const COMPOSE_FILE = 'infra/compose/compose.yaml';
export const OUTPUTS = {
  compose: 'infra/gateway/compose/dynamic.yaml',
  k8sRoutes: 'infra/k8s/base/gateway/routes.yaml',
  k8sMiddlewares: 'infra/k8s/base/gateway/middlewares.yaml',
  k8sConformanceRoutes: 'infra/k8s/components/conformance/routes.yaml',
};

const KNOWN_BACKENDS = new Set([
  'identity',
  'media',
  'notification',
  'payment',
  'web-3d',
  'object-store',
  'gateway-probe',
  'game',
]);
const DEFAULT_ENVIRONMENTS = ['compose', 'k8s'];
const ROUTE_ID = /^[a-z][a-z0-9-]*$/;
const API_PREFIX = /^\/api\/([a-z-]+)\/v[0-9]+(\/|$)/;
const K8S_NAMESPACE = 'netverse';
const GATEWAY_NAME = 'netverse';
const YAML_OPTIONS = { singleQuote: true };

export function loadRoutes(path = ROUTES_FILE) {
  return parse(readFileSync(path, 'utf8'));
}

function environmentsOf(route) {
  return route.environments ?? DEFAULT_ENVIRONMENTS;
}

function activeRoutes(doc, environment) {
  return doc.routes.filter(
    (route) => route.enabled !== false && environmentsOf(route).includes(environment),
  );
}

function prefixErrors(route) {
  const { id, prefix } = route;
  if (typeof prefix !== 'string' || !prefix.startsWith('/'))
    return [`${id}: prefix must start with /`];
  const errors = [];
  if (prefix !== '/' && prefix.endsWith('/')) errors.push(`${id}: prefix must not end with /`);
  if (prefix.includes('..') || prefix.includes('%') || prefix.includes('//')) {
    errors.push(`${id}: prefix must not contain .., % or //`);
  }
  return errors;
}

function isPathPrefixOf(base, path) {
  return path === base || path.startsWith(`${base}/`);
}

function apiRouteErrors(route) {
  const { id, prefix, strip } = route;
  if (route.entrypoint !== 'web' || prefix === '/' || prefix.startsWith('/ws/')) {
    if (strip !== undefined && !isPathPrefixOf(strip, prefix)) {
      return [`${id}: strip ${strip} is not a path prefix of ${prefix}`];
    }
    return [];
  }
  const match = API_PREFIX.exec(prefix);
  if (!match) return [`${id}: prefix ${prefix} must look like /api/<service>/v<n>`];
  const expected = `/api/${match[1]}`;
  return strip === expected ? [] : [`${id}: strip must be ${expected}`];
}

export function validateRoutes(doc) {
  const errors = [];
  const policies = doc.policies ?? {};
  const seenIds = new Set();
  const seenPrefixes = new Set();
  for (const route of doc.routes ?? []) {
    if (!ROUTE_ID.test(route.id ?? '')) errors.push(`invalid route id: ${route.id}`);
    if (seenIds.has(route.id)) errors.push(`duplicate route id: ${route.id}`);
    seenIds.add(route.id);
    if (!doc.entrypoints?.[route.entrypoint]) {
      errors.push(`${route.id}: unknown entrypoint ${route.entrypoint}`);
    }
    errors.push(...prefixErrors(route), ...apiRouteErrors(route));
    const key = `${route.entrypoint} ${route.prefix}`;
    if (seenPrefixes.has(key)) {
      errors.push(
        `${route.id}: duplicate prefix ${route.prefix} on entrypoint ${route.entrypoint}`,
      );
    }
    seenPrefixes.add(key);
    for (const policy of route.policies ?? []) {
      if (!policies[policy]) errors.push(`${route.id}: unknown policy ${policy}`);
    }
    if (!KNOWN_BACKENDS.has(route.backend?.service)) {
      errors.push(`${route.id}: unknown backend service ${route.backend?.service}`);
    }
  }
  return errors;
}

function withHeader(body) {
  return `${GENERATED_HEADER}\n${body}`;
}

function composeRule(prefix) {
  return prefix === '/' ? 'PathPrefix(`/`)' : `Path(\`${prefix}\`) || PathPrefix(\`${prefix}/\`)`;
}

function traefikMiddleware(policy) {
  if (policy.rateLimit) {
    return {
      rateLimit: {
        average: policy.rateLimit.average,
        period: policy.rateLimit.period,
        burst: policy.rateLimit.burst,
        sourceCriterion: { ipStrategy: { depth: 0 } },
      },
    };
  }
  if (policy.maxRequestBodyBytes !== undefined) {
    return { buffering: { maxRequestBodyBytes: policy.maxRequestBodyBytes } };
  }
  return {
    headers: {
      frameDeny: policy.frameDeny,
      contentTypeNosniff: policy.contentTypeNosniff,
      referrerPolicy: policy.referrerPolicy,
    },
  };
}

function usedPolicies(doc, routes) {
  const names = new Set(routes.flatMap((route) => route.policies ?? []));
  return Object.keys(doc.policies ?? {}).filter((name) => names.has(name));
}

export function renderCompose(doc) {
  const routes = activeRoutes(doc, 'compose');
  const routers = {};
  const services = {};
  const middlewares = {};
  for (const name of usedPolicies(doc, routes)) {
    middlewares[name] = traefikMiddleware(doc.policies[name]);
  }
  for (const route of routes) {
    const chain = [...(route.policies ?? [])];
    if (route.strip) {
      middlewares[`strip-${route.id}`] = { stripPrefix: { prefixes: [route.strip] } };
      chain.push(`strip-${route.id}`);
    }
    routers[route.id] = {
      entryPoints: [route.entrypoint],
      rule: composeRule(route.prefix),
      service: route.id,
      ...(chain.length > 0 ? { middlewares: chain } : {}),
      ...(route.priority !== undefined ? { priority: route.priority } : {}),
    };
    services[route.id] = {
      loadBalancer: {
        passHostHeader: true,
        servers: [{ url: `http://${route.backend.service}:${route.backend.port}` }],
      },
    };
  }
  return withHeader(stringify({ http: { routers, middlewares, services } }, YAML_OPTIONS));
}

function replacementPrefix(route) {
  const rest = route.prefix.slice(route.strip.length);
  return rest === '' ? '/' : rest;
}

function httpRoute(route) {
  const filters = (route.policies ?? []).map((name) => ({
    type: 'ExtensionRef',
    extensionRef: { group: 'traefik.io', kind: 'Middleware', name },
  }));
  if (route.strip) {
    filters.push({
      type: 'URLRewrite',
      urlRewrite: {
        path: { type: 'ReplacePrefixMatch', replacePrefixMatch: replacementPrefix(route) },
      },
    });
  }
  const backendRef = { name: route.backend.service };
  if (route.backend.namespace) backendRef.namespace = route.backend.namespace;
  backendRef.port = route.backend.port;
  return {
    apiVersion: 'gateway.networking.k8s.io/v1',
    kind: 'HTTPRoute',
    metadata: { name: route.id, namespace: K8S_NAMESPACE },
    spec: {
      parentRefs: [{ name: GATEWAY_NAME, sectionName: route.entrypoint }],
      rules: [
        {
          matches: [{ path: { type: 'PathPrefix', value: route.prefix } }],
          ...(filters.length > 0 ? { filters } : {}),
          backendRefs: [backendRef],
        },
      ],
    },
  };
}

function referenceGrant(route) {
  return {
    apiVersion: 'gateway.networking.k8s.io/v1beta1',
    kind: 'ReferenceGrant',
    metadata: { name: `${route.id}-from-gateway-routes`, namespace: route.backend.namespace },
    spec: {
      from: [{ group: 'gateway.networking.k8s.io', kind: 'HTTPRoute', namespace: K8S_NAMESPACE }],
      to: [{ group: '', kind: 'Service', name: route.backend.service }],
    },
  };
}

function multiDocument(objects) {
  return withHeader(objects.map((object) => stringify(object, YAML_OPTIONS)).join('---\n'));
}

export function renderKubernetes(doc, { environment }) {
  const objects = [];
  for (const route of activeRoutes(doc, environment)) {
    objects.push(httpRoute(route));
    if (route.backend.namespace && route.backend.namespace !== K8S_NAMESPACE) {
      objects.push(referenceGrant(route));
    }
  }
  return multiDocument(objects);
}

export function renderKubernetesMiddlewares(doc) {
  const routes = [...activeRoutes(doc, 'k8s'), ...activeRoutes(doc, 'k8s-conformance')];
  return multiDocument(
    usedPolicies(doc, routes).map((name) => ({
      apiVersion: 'traefik.io/v1alpha1',
      kind: 'Middleware',
      metadata: { name, namespace: K8S_NAMESPACE },
      spec: traefikMiddleware(doc.policies[name]),
    })),
  );
}

export function renderAll(doc) {
  return {
    [OUTPUTS.compose]: renderCompose(doc),
    [OUTPUTS.k8sRoutes]: renderKubernetes(doc, { environment: 'k8s' }),
    [OUTPUTS.k8sMiddlewares]: renderKubernetesMiddlewares(doc),
    [OUTPUTS.k8sConformanceRoutes]: renderKubernetes(doc, { environment: 'k8s-conformance' }),
  };
}

function trustsOneProxy(service) {
  const environment = service?.environment;
  if (!environment || Array.isArray(environment)) return false;
  return String(environment.TRUST_PROXY_HOPS) === '1';
}

function composeBackends(routesDoc, { apiOnly }) {
  const routes = activeRoutes(routesDoc, 'compose').filter(
    (route) => !apiOnly || route.prefix.startsWith('/api/'),
  );
  return [...new Set(routes.map((route) => route.backend.service))].sort();
}

export function findUntrustedBackends(routesDoc, composeDoc) {
  const services = composeDoc.services ?? {};
  return composeBackends(routesDoc, { apiOnly: true }).filter(
    (name) => services[name] && !trustsOneProxy(services[name]),
  );
}

export function findMissingBackends(routesDoc, composeDoc) {
  const services = composeDoc.services ?? {};
  return composeBackends(routesDoc, { apiOnly: false }).filter((name) => !services[name]);
}

export const STATIC_CONFIG_FILE = 'infra/gateway/compose/traefik.yaml';
const SENSITIVE_HEADERS = ['Authorization', 'Cookie', 'Set-Cookie'];

export function validateStaticConfig(config) {
  const errors = [];
  if (config.api?.dashboard !== false) errors.push('api.dashboard must be false');
  if (config.api?.insecure === true) errors.push('api.insecure must not be enabled');
  if (config.providers?.docker) errors.push('providers.docker must not be used');
  for (const [name, entryPoint] of Object.entries(config.entryPoints ?? {})) {
    const forwarded = entryPoint.forwardedHeaders ?? {};
    if (forwarded.insecure === true || (forwarded.trustedIPs ?? []).length > 0) {
      errors.push(`entryPoints.${name} must not trust client forwarded headers`);
    }
  }
  const headers = config.accessLog?.fields?.headers;
  if (headers && headers.defaultMode !== 'drop') {
    errors.push('accessLog.fields.headers.defaultMode must be drop');
  }
  for (const header of SENSITIVE_HEADERS) {
    if (headers?.names?.[header] && headers.names[header] !== 'drop') {
      errors.push(`accessLog must not keep the ${header} header`);
    }
  }
  return errors;
}
